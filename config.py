# ENABLED_TOPICS=sto,realestate 처럼 env로 토픽 on/off (미지정 시 전체 시도)
_enabled_raw = os.getenv("ENABLED_TOPICS", "").strip()
ENABLED_TOPICS = _split_csv(_enabled_raw) or list(TOPICS.keys())


def active_topics() -> dict[str, dict]:
    """실제로 구동할 토픽만 반환 (활성 목록에 있고, 봇토큰+채널이 갖춰진 것)."""
    result = {}
    for key in ENABLED_TOPICS:
        profile = TOPICS.get(key)
        if not profile:
            continue
        if profile["bot_token"] and profile["chat_ids"]:
            result[key] = profile
    return result


def topic_status() -> list[str]:
    """각 토픽의 활성/비활성 사유 (로그용)."""
    lines = []
    for key in ENABLED_TOPICS:
        profile = TOPICS.get(key)
        if not profile:
            lines.append(f"{key}: 알 수 없는 토픽")
        elif not profile["bot_token"]:
            lines.append(f"{key}: 비활성(봇 토큰 없음)")
        elif not profile["chat_ids"]:
            lines.append(f"{key}: 비활성(채팅방 ID 없음)")
        else:
            lines.append(f"{key}: 활성 (채널 {len(profile['chat_ids'])}개)")
    return lines


def validate_config():
    """Naver 키 필수 + 최소 1개 토픽 구동 가능해야 함."""
    missing = []
    if not NAVER_CLIENT_ID:
        missing.append("NAVER_CLIENT_ID")
    if not NAVER_CLIENT_SECRET:
        missing.append("NAVER_CLIENT_SECRET")
    if missing:
        raise EnvironmentError(f"누락된 환경변수: {', '.join(missing)}\n.env 파일을 확인하세요.")
    if not active_topics():
        raise EnvironmentError(
            "구동 가능한 토픽이 없습니다. 각 토픽의 봇 토큰/채팅방 ID를 .env에 설정하세요.\n"
            + "\n".join("  - " + s for s in topic_status())
        )
